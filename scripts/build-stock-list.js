// Builds web/stock-tokens.json: every stock token created by Robinhood's StockFactory on Robinhood
// Chain mainnet, read from the factory's own creation events. Nothing is typed in by hand.
//
//   node scripts/build-stock-list.js            scan from where the last run stopped
//   node scripts/build-stock-list.js --full     rescan from block 0
//
// The factory emits one event per token: (address token, string name, string symbol). The RPC
// allows 10,001 blocks per log query, so the scan runs in parallel chunks and saves its progress.
const fs = require("fs");
const path = require("path");

const RPCS = ["https://robinhood.api.pocket.network", "https://rpc.mainnet.chain.robinhood.com"];
const FACTORY = "0x4783c67b63de2b358ac5951a7d41f47a38f3c046";
const BEACON = "0xe10b6f6b275de231345c20d14ab812db62151b00";
const SPAN = 10000;
const PAR = 8;
const OUT = path.join(__dirname, "..", "web", "stock-tokens.json");

let id = 1;
async function rpc(method, params) {
  let last;
  for (let attempt = 0; attempt < 6; attempt++) {
    const url = RPCS[attempt % RPCS.length];
    try {
      const ctl = new AbortController();
      const timer = setTimeout(() => ctl.abort(), 20000);
      const r = await fetch(url, { method: "POST", signal: ctl.signal, headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: id++, method, params }) });
      clearTimeout(timer);
      const j = await r.json();
      if (j.error) throw new Error(j.error.message);
      return j.result;
    } catch (e) { last = e; await new Promise((res) => setTimeout(res, 500 * (attempt + 1))); }
  }
  throw new Error(`${method}: ${last && last.message}`);
}

function decode(data) {
  const b = Buffer.from(data.slice(2), "hex");
  const word = (i) => b.slice(i * 32, i * 32 + 32);
  const str = (off) => { const len = Number(b.readBigUInt64BE(off + 24)); return b.slice(off + 32, off + 32 + len).toString("utf8"); };
  return {
    address: "0x" + word(0).slice(12).toString("hex"),
    name: str(Number(word(1).readBigUInt64BE(24))),
    symbol: str(Number(word(2).readBigUInt64BE(24))),
  };
}

const hex = (n) => "0x" + n.toString(16);

(async () => {
  const full = process.argv.includes("--full");
  const prev = !full && fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, "utf8")) : null;
  const byAddr = new Map((prev ? prev.tokens : []).map((t) => [t.address, t]));
  const start = prev ? prev.scannedTo + 1 : 0;
  const head = parseInt(await rpc("eth_blockNumber", []), 16);
  const chunks = [];
  for (let f = start; f <= head; f += SPAN) chunks.push([f, Math.min(head, f + SPAN - 1)]);
  const total = chunks.length;
  console.log(`scanning blocks ${start}..${head} in ${total} chunks`);

  let done = 0;
  const t0 = Date.now();
  const tries = new Map();
  async function worker() {
    while (chunks.length) {
      const c = chunks.shift();
      const [f, t] = c;
      let logs;
      try {
        logs = await rpc("eth_getLogs", [{ fromBlock: hex(f), toBlock: hex(t), address: FACTORY }]);
      } catch (e) {
        // a busy or slow node: put the chunk back and try it again later
        const n = (tries.get(f) || 0) + 1;
        if (n > 8) throw e;
        tries.set(f, n);
        chunks.push(c);
        await new Promise((res) => setTimeout(res, 2000 * n));
        continue;
      }
      for (const l of logs) {
        if (l.data.length < 2 + 64 * 5) continue; // not a creation event
        let ev;
        try { ev = decode(l.data); } catch { continue; }
        byAddr.set(ev.address, { ...ev, block: parseInt(l.blockNumber, 16), tx: l.transactionHash });
      }
      if (++done % 500 === 0) console.log(`  ${done}/${total} chunks, ${byAddr.size} tokens, ${Math.round((Date.now() - t0) / 1000)} s`);
    }
  }
  await Promise.all(Array.from({ length: PAR }, worker));

  // check each one on-chain: it is a proxy of Robinhood's stock-token beacon and answers the same name
  const tokens = [];
  for (const t of [...byAddr.values()].sort((a, b) => a.symbol.localeCompare(b.symbol))) {
    const slot = await rpc("eth_getStorageAt", [t.address, "0xa3f0ad74e5423aebfd80d3ef4346578335a9a72aeaee59ff6cb3582b35133d50", "latest"]);
    if ("0x" + slot.slice(-40) !== BEACON) { console.log(`  skipped ${t.symbol} ${t.address}: not on the stock-token beacon`); continue; }
    tokens.push(t);
  }
  const out = {
    note: "Stock tokens created by Robinhood's StockFactory on Robinhood Chain mainnet, read from the factory's creation events. Generated by scripts/build-stock-list.js.",
    chainId: 4663, factory: FACTORY, beacon: BEACON, scannedTo: head, updated: new Date().toISOString(), tokens,
  };
  fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + "\n");
  // The same list as a script, for check.js in the browser and in the Netlify functions.
  fs.writeFileSync(OUT.replace(/\.json$/, ".js"), `/* Generated by scripts/build-stock-list.js. Do not edit by hand. */\n(function (g) { g.NearlStockTokens = ${JSON.stringify({ chainId: out.chainId, factory: FACTORY, beacon: BEACON, scannedTo: head, updated: out.updated, tokens: tokens.map(({ address, name, symbol, block }) => ({ address, name, symbol, block })) })}; })(typeof window !== "undefined" ? window : globalThis);\n`);
  console.log(`saved ${tokens.length} tokens to web/stock-tokens.json and web/stock-tokens.js (scanned to block ${head})`);
})().catch((e) => { console.error(e); process.exit(1); });
