// Copies the compiled probe runtime bytecode into web/probe-code.js for NEARL Check.
// Run after `npx hardhat compile`: node scripts/build-probe.js
const fs = require("fs");
const path = require("path");
const v3 = require("../artifacts/contracts/tools/Probe.sol/Probe.json");
const v4 = require("../artifacts/contracts/tools/ProbeV4.sol/ProbeV4.json");
const pons = require("../artifacts/contracts/tools/ProbePons.sol/ProbePons.json");
const out = path.join(__dirname, "..", "web", "probe-code.js");
fs.writeFileSync(
  out,
  `// Generated by scripts/build-probe.js from contracts/tools/Probe.sol, ProbeV4.sol and ProbePons.sol. Do not edit.\n` +
    `window.NEARL_PROBE = "${v3.deployedBytecode}";\n` +
    `window.NEARL_PROBE_V4 = "${v4.deployedBytecode}";\n` +
    `window.NEARL_PROBE_PONS = "${pons.deployedBytecode}";\n`,
);
console.log(`Wrote ${path.relative(process.cwd(), out)}`);
